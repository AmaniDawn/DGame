#!/usr/bin/env python3
"""Run the official Luban Agent CLI / MCP against this DGame checkout."""

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tomllib


REPO = Path(__file__).resolve().parents[4]
TOOLS = REPO / "GameConfig/Tools/LubanTools/AI"
QUERY_TOOLS = ("list_tables", "get_schema", "describe", "validate")


def check_install():
    lock = json.loads(Path(__file__).with_name("ai-tools.lock.json").read_text(encoding="utf-8"))
    manifest_path = TOOLS / "install.json"
    if not manifest_path.is_file():
        raise ValueError("Run python .agents/skills/luban-dev/scripts/install_ai_tools.py first")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("commit") != lock["commit"]:
        raise ValueError("Installed Luban AI does not match ai-tools.lock.json")
    for name in ("Luban.Agent", "Luban.Mcp", "Luban"):
        if not (TOOLS / f"{name}/{name}.dll").is_file():
            raise ValueError(f"Missing official tool: {name}")


def configure_mcp():
    """Write a portable project Codex configuration, preserving existing settings."""
    path = REPO / ".codex/config.toml"
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    config = tomllib.loads(text)
    server = {
        "command": "python",
        "args": [".agents/skills/luban-dev/scripts/luban_ai.py", "mcp"],
        "enabled_tools": list(QUERY_TOOLS),
        "startup_timeout_sec": 30,
        "tool_timeout_sec": 120,
    }
    existing = config.get("mcp_servers", {}).get("luban")
    if existing is not None:
        if existing != server:
            raise ValueError(f"Existing [mcp_servers.luban] differs; review {path} before changing it")
        print(f"Luban MCP is already configured in {path}")
        return
    stanza = "\n# Luban uses the workspace root; generated by luban_ai.py configure-mcp.\n"
    stanza += "[mcp_servers.luban]\n"
    stanza += "".join(f"{key} = {json.dumps(value, ensure_ascii=False)}\n" for key, value in server.items())
    path.parent.mkdir(exist_ok=True)
    path.write_text(text.rstrip() + "\n" + stanza, encoding="utf-8")
    print(f"Configured Luban MCP in {path}. New sessions load this project configuration.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("capabilities", "list-tables", "describe", "schema", "validate",
                                         "mcp", "configure-mcp"))
    parser.add_argument("--target", choices=("client", "server", "all"), default="client")
    parser.add_argument("--name", help="Table/bean/enum name for describe or schema filtering")
    args = parser.parse_args()
    check_install()
    if args.mode == "configure-mcp":
        configure_mcp()
        return 0
    if args.mode == "mcp":
        env = {**os.environ, "LUBAN_AGENT_DLL": str(TOOLS / "Luban.Agent/Luban.Agent.dll"),
               "LUBAN_DLL": str(TOOLS / "Luban/Luban.dll")}
        # The official server's Agent child reads nlog.xml from cwd; keep its diagnostics on stderr.
        return subprocess.call(["dotnet", str(TOOLS / "Luban.Mcp/Luban.Mcp.dll")],
                               cwd=TOOLS / "Luban.Agent", env=env)
    command = ["dotnet", str(TOOLS / "Luban.Agent/Luban.Agent.dll"), args.mode]
    if args.mode != "capabilities":
        command += ["--conf", str(REPO / "GameConfig/luban.conf"), "-t", args.target]
    if args.name:
        command += ["--name", args.name]
    # The official Agent loads nlog.xml relative to cwd; use its stderr-only logger.
    command += ["--logConfig", str(TOOLS / "Luban.Agent/nlog.xml")]
    return subprocess.call(command, cwd=REPO)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(2)
